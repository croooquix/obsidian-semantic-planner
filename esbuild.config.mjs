import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFile, writeFile } from "fs/promises";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin.
*/
`;

const prod = (process.argv[2] === "production");

// ★ 플러그인 1: onnxruntime-node를 빈 모듈로 대체
const shimOnnxNativePlugin = {
	name: "shim-onnxruntime-node",
	setup(build) {
		build.onResolve({ filter: /^onnxruntime-node$/ }, (args) => {
			return { path: args.path, namespace: "shim-onnxruntime-node" };
		});
		build.onLoad({ filter: /.*/, namespace: "shim-onnxruntime-node" }, () => {
			return { contents: "module.exports = {};", loader: "js" };
		});
	},
};

// ★ 플러그인 2: sharp (이미지 처리) 빈 모듈 대체
const shimSharpPlugin = {
	name: "shim-sharp",
	setup(build) {
		build.onResolve({ filter: /^sharp$/ }, (args) => {
			return { path: args.path, namespace: "shim-sharp" };
		});
		build.onLoad({ filter: /.*/, namespace: "shim-sharp" }, () => {
			return { contents: "module.exports = {};", loader: "js" };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	plugins: [shimOnnxNativePlugin, shimSharpPlugin],
	external: [
		"obsidian",
		"electron",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		...builtins,
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	define: {
		"import.meta.url": "\"file:///C:/\"",
	},
});

if (prod) {
	await context.rebuild();

	// ★ 빌드 후처리: 번들된 main.js에서 process.release.name === "node" 조건을 false로 패치
	// 옵시디언(Electron)은 process.release.name이 "node"로 평가되므로
	// transformers.js가 네이티브 onnxruntime-node(빈 shim)를 선택해 버리는 것을 방지
	// → 항상 onnxruntime-web (WASM) 백엔드로 진입하도록 강제
	let code = await readFile("main.js", "utf8");
	code = code.replaceAll(
		'process?.release?.name === "node"',
		"false /* patched: force WASM backend */"
	);
	await writeFile("main.js", code, "utf8");
	console.log("[post-build] Patched process.release.name checks → forced WASM backend");

	process.exit(0);
} else {
	await context.watch();
}
